"""Week 5: writes the constant tables of the C++ log-mel front end.

firmware/lib/zt_logmel/zt_logmel_tables.h holds the cos/sin table of the 1024-point FFT
(the Hann window is derived from it) and the 64 mel filters as librosa builds them, stored
without their zeros. Everything follows from src/audio_config.py alone, no data and no
model, so this header IS committed. Run again only if the audio settings change;
src/test_cpp_logmel.py fails when the committed header is out of date.

Usage:
    python src/export_logmel_tables.py
"""

import librosa
import numpy as np

import audio_config as C
from dataset import ROOT
from export_factory import c_array

OUT = ROOT / "firmware" / "lib" / "zt_logmel" / "zt_logmel_tables.h"


def int_array(a, per_line: int = 16, indent: str = "    ") -> str:
    items = [str(int(v)) for v in a]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "{\n" + indent + (",\n" + indent).join(lines) + "}"


def tables_text() -> str:
    assert C.WINDOW == "hann" and C.POWER == 2.0 and not C.CENTER, "the C++ code assumes these"
    k = np.arange(C.N_FFT // 2)
    cos = np.cos(2 * np.pi * k / C.N_FFT).astype(np.float32)
    sin = np.sin(2 * np.pi * k / C.N_FFT).astype(np.float32)
    mel = librosa.filters.mel(sr=C.SR, n_fft=C.N_FFT, n_mels=C.N_MELS, fmin=C.FMIN, fmax=C.FMAX,
                              htk=C.MEL_HTK, norm=C.MEL_NORM)
    start, length, weights = [], [], []
    for row in mel:
        nz = np.flatnonzero(row)
        assert (row[nz[0]:nz[-1] + 1] > 0).all(), "mel filter with a gap"
        start.append(nz[0])
        length.append(nz[-1] - nz[0] + 1)
        weights.append(row[nz[0]:nz[-1] + 1])
    weights = np.concatenate(weights)
    fa = lambda a: c_array(a, indent="    ").replace("{", "{\n    ", 1)
    return f"""// Generated by src/export_logmel_tables.py from src/audio_config.py. Do not edit.
// {C.SR} Hz, n_fft {C.N_FFT}, {C.N_MELS} mel bands {C.FMIN:.0f}-{C.FMAX:.0f} Hz (Slaney scale and norm).
#ifndef ZT_LOGMEL_TABLES_H
#define ZT_LOGMEL_TABLES_H

#include <stdint.h>

const int ZT_TABLE_SR = {C.SR};
const int ZT_TABLE_N_FFT = {C.N_FFT};
const int ZT_TABLE_N_MELS = {C.N_MELS};

// cos(2*pi*k/{C.N_FFT}) and sin(2*pi*k/{C.N_FFT}) for k = 0..{C.N_FFT // 2 - 1}
static const float ZT_COS[{len(cos)}] = {fa(cos)};

static const float ZT_SIN[{len(sin)}] = {fa(sin)};

// Mel filter m covers the FFT bins ZT_MEL_START[m] .. ZT_MEL_START[m] + ZT_MEL_LEN[m] - 1.
// Its weights follow each other in ZT_MEL_W.
static const uint16_t ZT_MEL_START[{len(start)}] = {int_array(start)};

static const uint16_t ZT_MEL_LEN[{len(length)}] = {int_array(length)};

static const float ZT_MEL_W[{len(weights)}] = {fa(weights)};

#endif
"""


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(tables_text(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} kB of text)")
