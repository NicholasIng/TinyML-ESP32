"""Week 5: writes the factory constants the firmware needs as a C++ header.

The calibration on the ESP32 (firmware/lib/zt_calib) starts from a few numbers measured on
the PC: 32 factory means, 32 factory variances, and three small tables found by rehearsing
the calibration on factory data (calibration.fit_source). This script computes them with
the int8 model and writes firmware/generated/zt_factory.h, together with the int8 scale and
zero point of the model's input and output. The header is generated, so it is not committed.

Usage:
    python src/export_factory.py                       # fan_v1_int8, all four fans at 6 dB
    python src/export_factory.py --burn-clips 6        # 1 min burn-in instead of 5 min
"""

import argparse
import json

import numpy as np

import calibration as cal
from dataset import IDS, ROOT

BURN_METHOD = {clips: name for name, clips in cal.BURN.items()}   # 6 -> burn_1min, 30 -> burn_5min


def factory_fields(src: cal.SourceModel, n0: float = cal.N0, burn_clips: int = 30) -> dict:
    """The fields of the C++ struct zt::Factory, in struct order.
    burn_clips = 0 means no burn-in: the device then uses thr_table only."""
    method = BURN_METHOD[burn_clips or 30]
    return {
        "mu": np.asarray(src.mu, np.float32),
        "var": np.asarray(src.var, np.float32),
        "n0": np.float32(n0),
        "burn_clips": int(burn_clips),
        "seconds": np.asarray(cal.SECONDS, np.float32),
        "thr_table": np.asarray([src.thr_table["centroid_var_cal"][s] for s in cal.SECONDS], np.float32),
        "k_clip": np.asarray([src.k_burn[method][s] for s in cal.SECONDS], np.float32),
        "k_vote": np.asarray([src.k_vote[method][s] for s in cal.SECONDS], np.float32),
    }


def c_float(v) -> str:
    """A float32 as a C literal that reads back as exactly the same float32."""
    s = f"{float(np.float32(v)):.9g}"
    if not any(c in s for c in ".en"):
        s += ".0"
    return s + "f"


def c_array(a, per_line: int = 6, indent: str = "     ") -> str:
    items = [c_float(v) for v in a]
    lines = [", ".join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
    return "{" + (",\n" + indent).join(lines) + "}"


def header(fields: dict, meta: dict, comment: str) -> str:
    f = fields
    return f"""// Generated by src/export_factory.py. Do not edit, do not commit.
// {comment}
#ifndef ZT_FACTORY_H
#define ZT_FACTORY_H

#include "zt_calib.h"

// int8 model input:  q = clamp(round(dB / ZT_IN_SCALE) + ZT_IN_ZERO, -128, 127)
// int8 model output: emb = (q - ZT_EMB_ZERO) * ZT_EMB_SCALE   (zt::dequantize)
static const float ZT_IN_SCALE = {c_float(meta["in_scale"])};
static const int ZT_IN_ZERO = {int(meta["in_zero"])};
static const float ZT_EMB_SCALE = {c_float(meta["out_scale"])};
static const int ZT_EMB_ZERO = {int(meta["out_zero"])};

static const zt::Factory ZT_FACTORY = {{
    // mu
    {c_array(f["mu"])},
    // var
    {c_array(f["var"])},
    {c_float(f["n0"])},   // n0
    {f["burn_clips"]},   // burn_clips
    {c_array(f["seconds"])},   // seconds
    {c_array(f["thr_table"])},   // thr_table
    {c_array(f["k_clip"])},   // k_clip
    {c_array(f["k_vote"])},   // k_vote
}};

#endif
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="fan_v1_int8")
    ap.add_argument("--snr", default="6dB", help="noise level of the factory data")
    ap.add_argument("--ids", nargs="+", default=IDS, help="factory machines")
    ap.add_argument("--burn-clips", type=int, default=30, choices=[0, *BURN_METHOD],
                    help="burn-in length in 10 s clips (0 = no burn-in)")
    ap.add_argument("--n0", type=float, default=cal.N0)
    ap.add_argument("--out", default=str(ROOT / "firmware" / "generated" / "zt_factory.h"))
    args = ap.parse_args()

    from evaluate import feature_bank   # imports TensorFlow, so only when needed
    from pathlib import Path

    bank = feature_bank(args.model)
    groups = [bank(args.snr, m, "train")["emb"] for m in args.ids]
    src = cal.fit_source(groups, args.n0)
    fields = factory_fields(src, args.n0, args.burn_clips)
    meta = json.loads((ROOT / "models" / f"{args.model}.json").read_text())
    comment = (f"model {args.model}, factory data {args.snr} x {' '.join(args.ids)} "
               f"({sum(len(g) for g in groups)} windows)")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header(fields, meta, comment), encoding="utf-8")
    print(f"wrote {out}")
    print(comment)
    print("calibration seconds  ", cal.SECONDS)
    print("thr_table            ", np.round(fields["thr_table"], 3))
    print("k_clip (5% per clip) ", np.round(fields["k_clip"], 3))
    print("k_vote (20% per clip)", np.round(fields["k_vote"], 3))


if __name__ == "__main__":
    main()
