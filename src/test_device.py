"""Week 6b: runs the whole chain on the ESP32-S3 and compares it with Python.

The firmware firmware/device_test has a few MIMII clips stored in its flash. On the board
it runs exactly what the final device runs: log-mel (zt_logmel) -> int8 model (TensorFlow
Lite Micro) -> calibration and anomaly score (zt_calib). It prints every model input,
every embedding, the clip scores, the time each step takes and the memory used. This
script computes the same in Python (features.py + the TFLite interpreter) and compares.

Usage:
    python src/test_device.py --prepare      # writes the generated files the firmware needs
    (cd firmware/device_test && pio run -t upload)
    python src/test_device.py                # resets the board, reads its output, compares

--prepare writes into firmware/generated/ (not committed): zt_model_data.h (the .tflite
model as a C array), zt_factory.h (factory constants, as src/export_factory.py),
bench_clips.raw (16-bit audio of the test clips) and bench_clips.json (which clips).
"""

import argparse
import json
import sys
import time

import numpy as np

import calibration as cal
from dataset import ROOT
from features import load_wav, windows

GEN = ROOT / "firmware" / "generated"
MODEL = "fan_v1_int8"
# (noise level, machine, label, index in the sorted file list). The first clip is used as
# the calibration audio on the board (10 s of "verified normal" sound).
CLIPS = [("6dB", "id_00", "normal", 0), ("6dB", "id_00", "normal", 1),
         ("6dB", "id_00", "abnormal", 0), ("6dB", "id_00", "abnormal", 1),
         ("-6dB", "id_02", "normal", 0), ("-6dB", "id_02", "abnormal", 0)]
CLIP_SAMPLES = 160_000
WINS = cal.WINS


def clip_paths():
    out = []
    for snr, mid, label, i in CLIPS:
        out.append(sorted((ROOT / "data" / snr / "fan" / mid / label).glob("*.wav"))[i])
    return out


def prepare():
    import export_factory as ef
    from evaluate import feature_bank
    from dataset import IDS

    GEN.mkdir(parents=True, exist_ok=True)
    # 1. the model as a C array, 16-byte aligned as TensorFlow Lite Micro expects
    data = (ROOT / "models" / f"{MODEL}.tflite").read_bytes()
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    (GEN / "zt_model_data.h").write_text(
        f"// Generated by src/test_device.py from models/{MODEL}.tflite. Do not commit.\n"
        "#ifndef ZT_MODEL_DATA_H\n#define ZT_MODEL_DATA_H\n\n"
        f"alignas(16) static const unsigned char ZT_MODEL[{len(data)}] = {{\n  "
        + ",\n  ".join(rows) + "};\n\n#endif\n", encoding="utf-8", newline="\n")

    # 2. factory constants (same as src/export_factory.py with its defaults)
    bank = feature_bank(MODEL)
    src = cal.fit_source([bank("6dB", m, "train")["emb"] for m in IDS])
    fields = ef.factory_fields(src)
    meta = json.loads((ROOT / "models" / f"{MODEL}.json").read_text())
    (GEN / "zt_factory.h").write_text(
        ef.header(fields, meta, f"model {MODEL}, factory data 6dB x {' '.join(IDS)}"),
        encoding="utf-8")

    # 3. test audio: the 16-bit samples exactly as stored in the wav files
    pcm = []
    for p in clip_paths():
        v = load_wav(p) * 32768.0
        assert len(v) == CLIP_SAMPLES and np.all(v == np.round(v)), p
        pcm.append(v.astype("<i2"))
    np.concatenate(pcm).tofile(GEN / "bench_clips.raw")
    (GEN / "bench_clips.json").write_text(json.dumps({
        "clips": [str(p.relative_to(ROOT)) for p in clip_paths()],
        "mu": fields["mu"].tolist(), "var": fields["var"].tolist(), "n0": float(fields["n0"]),
    }, indent=1))
    print(f"wrote {GEN}: zt_model_data.h ({len(data)} bytes), zt_factory.h, "
          f"bench_clips.raw ({len(CLIPS)} clips, {len(CLIPS) * CLIP_SAMPLES * 2 / 1e6:.2f} MB)")


def read_board(port: str, timeout: float = 180):
    """Resets the board and returns its output lines up to "D done"."""
    from mic_record import open_port
    lines = []
    with open_port(port) as s:
        s.rts = True             # EN low: reset (DTR stays low, so it boots normally)
        time.sleep(0.1)
        s.reset_input_buffer()
        s.rts = False
        t0 = time.time()
        while time.time() - t0 < timeout:
            line = s.readline().decode("ascii", "replace").strip()
            if not line:
                continue
            if line[0] in "ITMSX" or line.startswith("D "):
                print(f"  board: {line}")
            lines.append(line)
            if line.startswith(("D done", "X ")):
                return lines
    sys.exit("No 'D done' from the board. Is firmware/device_test flashed?")


def parse(lines):
    q, e, s = {}, {}, {}
    for line in lines:
        p = line.split()
        if line.startswith(("Q ", "E ")) and len(p) == 4:
            arr = np.frombuffer(bytes.fromhex(p[3]), np.int8)
            (q if p[0] == "Q" else e)[int(p[1]), int(p[2])] = arr
        elif line.startswith("S ") and len(p) == 4:
            s[int(p[1])] = (float(p[2]), float(p[3]))
    return q, e, s


def compare(lines):
    from tflite_runner import Int8Embedder

    info = json.loads((GEN / "bench_clips.json").read_text())
    mu, var, n0 = np.array(info["mu"]), np.array(info["var"]), info["n0"]
    net = Int8Embedder(ROOT / "models" / f"{MODEL}.tflite")
    ref = Int8Embedder(ROOT / "models" / f"{MODEL}.tflite", reference=True)
    q_dev, e_dev, s_dev = parse(lines)
    n_clips = len(info["clips"])
    assert len(q_dev) == len(e_dev) == n_clips * WINS, (len(q_dev), len(e_dev))

    q_diff = q_max = e_diff = e_max = e_same_in_diff = e_ref_diff = 0
    emb_py, emb_dev = [], []
    for c, path in enumerate(info["clips"]):
        q_py = net.quantize(windows(load_wav(ROOT / path))[:WINS])          # (10, 64, 30)
        qd = np.stack([q_dev[c, w] for w in range(WINS)]).reshape(q_py.shape)
        d = np.abs(qd.astype(int) - q_py.astype(int))
        q_diff, q_max = q_diff + int((d > 0).sum()), max(q_max, int(d.max()))
        e_py = net.predict_int8(q_py[..., None])                            # Python all the way
        e_py_devin = net.predict_int8(qd[..., None])                        # Python model, board input
        ed = np.stack([e_dev[c, w] for w in range(WINS)])
        d = np.abs(ed.astype(int) - e_py.astype(int))
        e_diff, e_max = e_diff + int((d > 0).sum()), max(e_max, int(d.max()))
        e_same_in_diff += int((ed != e_py_devin).sum())
        e_ref_diff += int((ed != ref.predict_int8(qd[..., None])).sum())  # PC reference kernels
        f = lambda z: (z.astype(np.float32) - net.out_zero) * net.out_scale
        emb_py.append(f(e_py))
        emb_dev.append(f(ed))

    # scores: factory model, and the model calibrated on the first clip (10 s)
    x0 = emb_py[0]
    mu_c, var_c = x0.mean(axis=0), cal._mixed_var(var, x0, n0)
    print(f"\n{n_clips} clips, {n_clips * WINS} windows: board vs Python")
    print(f"  int8 model input values that differ   {q_diff} of {n_clips * WINS * 1920}, "
          f"never by more than {q_max}")
    print(f"  int8 embedding values that differ     {e_diff} of {n_clips * WINS * 32}, "
          f"never by more than {e_max}")
    print(f"  ... with the board's own model input  {e_same_in_diff} differ "
          f"(TFLite Micro on the board vs TFLite on the PC)")
    print(f"  ... vs TFLite reference kernels on PC {e_ref_diff} differ")
    print(f"  clip scores (factory model | calibrated on clip 0):")
    worst = 0.0
    for c, path in enumerate(info["clips"]):
        py = (cal.clip_scores(emb_py[c], mu, var)[0], cal.clip_scores(emb_py[c], mu_c, var_c)[0])
        dv = s_dev[c]
        rel = max(abs(dv[i] - py[i]) / py[i] for i in range(2))
        worst = max(worst, rel)
        print(f"    {path[5:]:44s} board {dv[0]:8.3f} | {dv[1]:8.3f}   python {py[0]:8.3f} | "
              f"{py[1]:8.3f}   diff {100 * rel:.3f}%")
    print(f"  largest clip score difference         {100 * worst:.3f}%")
    ok = q_max <= 1 and q_diff / (n_clips * WINS * 1920) < 0.01 and worst < 0.02
    print("PASS" if ok else "FAIL")
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prepare", action="store_true")
    ap.add_argument("--port")
    args = ap.parse_args()
    if args.prepare:
        prepare()
        return
    from mic_record import find_port
    lines = read_board(args.port or find_port())
    sys.exit(0 if compare(lines) else 1)


if __name__ == "__main__":
    main()
